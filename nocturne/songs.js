// every note of a song on one timeline (beats): right hand with its index, left hand apart
export function timeline(id) {
  const s = SONGS[id], rh = [], lh = [];
  let t = s.start || 0;
  s.mel.forEach(([m, d], i) => { rh.push({ t, m, d, i }); t += d; });
  if (s.lhEv) for (const [bt, m, d] of s.lhEv) lh.push({ t: bt, m, d });
  else { let tl = 0; for (const [c, d] of s.lh || []) { for (const m of c) lh.push({ t: tl, m, d }); tl += d; } }
  // the prelude: each right-hand group starts two sixteenths into its half bar
  if (id === 'prelude') { let k = 0; for (let half = 0; half < 16; half++) for (let j = 0; j < 6; j++) rh[k++].t = half * 8 + 2 + j; }
  const end = Math.max(t, ...lh.map((e) => e.t + e.d));
  return { rh, lh, end };
}
